/** Format a measure for display with Western digits (spec §7.3). */
export function fmt(value, unitAr) {
  if (value === null || value === undefined) return 'غير متاح';
  if (unitAr === '%') return `${(value * 100).toFixed(1)}%`;
  if (unitAr === 'يوم') return `${Math.round(value)} يوم`;
  if (unitAr === 'مرة') return `${value.toFixed(2)} مرة`;
  const s = Math.abs(value).toLocaleString('en-US', { maximumFractionDigits: 2 });
  return value < 0 ? `(${s})` : s;
}
